import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.resolve(packageRoot, "..", "..", "templates", "runtime");
const destination = path.join(packageRoot, "src", "runtime", "templates.ts");

const entries = (await readdir(sourceDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith(".template.md"))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right));

if (entries.length === 0) {
  throw new Error(`No runtime templates found in ${sourceDirectory}`);
}

const blocks = [];
for (const fileName of entries) {
  const name = fileName.replace(/\.template\.md$/, "");
  const body = (await readFile(path.join(sourceDirectory, fileName), "utf8")).replace(/\s+$/, "");
  blocks.push(`  template(\n    ${JSON.stringify(name)},\n    ${JSON.stringify(`${body}\n`)},\n  )`);
}

const contents = `import type { RuntimeAsset } from "../types.js";

const marker = "<!-- Generated by mstack. Regenerate instead of editing. -->";

function template(name: string, content: string): RuntimeAsset {
  return {
    id: \`\${name}-template\`,
    version: "1.1.0",
    activation: "passive",
    security: "content",
    feature: "templates",
    path: \`.mstack/templates/\${name}.template.md\`,
    content: \`\${marker}\\n\\n\${content.trim()}\`,
  };
}

/** Sourced from templates/runtime/*.template.md — run \`pnpm run sync-runtime-templates\`. */
export const runtimeTemplates: readonly RuntimeAsset[] = [
${blocks.join(",\n")},
];
`;

await writeFile(destination, contents, "utf8");
console.log(`Synced ${entries.length} runtime templates into ${path.relative(packageRoot, destination)}`);
