import type { SkillDefinition } from "../types.js";

interface PlaybookSource {
  readonly id: string;
  readonly title: string;
  readonly description: string;
  readonly match: string;
  readonly ownership: string;
  readonly goalShape: string;
  readonly finishCondition: string;
  readonly evidence: string;
  readonly constraints: readonly string[];
  readonly steps: readonly string[];
  readonly principles: readonly string[];
  readonly reply: string;
}

function definePlaybook(source: PlaybookSource): SkillDefinition {
  return {
    id: source.id,
    version: "1.1.0",
    activation: "explicit",
    security: "content",
    fallback: "degrade",
    description: source.description,
    constraints: { kind: "playbook" },
    instructions: [
      `# ${source.title}`,
      "",
      source.ownership,
      "",
      "## Prompt shape",
      "",
      `- **Goal:** ${source.goalShape}`,
      `- **Finish condition:** ${source.finishCondition}`,
      `- **Evidence:** ${source.evidence}`,
      `- **Constraints:** ${source.constraints.join("; ")}`,
      "",
      "## Match",
      "",
      source.match,
      "",
      "## Steps",
      "",
      "Copy these steps into the todo list word for word. Mark skips as `skip: <reason>`.",
      "",
      ...source.steps.map((step, index) => `${index + 1}. ${step}`),
      "",
      "## Principles to cite by name",
      "",
      ...source.principles.map((id) => `- \`${id}\``),
      "",
      `**Reply:** ${source.reply}`,
    ].join("\n"),
  };
}

