import type { AgentDefinition, HookDefinition, IntegrationSpec, PromptDefinition, RuntimeAsset, SkillDefinition } from "../types.js";
import { renderAgentMarkdown, renderInstructionBody, renderPromptSkill, renderStandardSkill, yamlString } from "../adapters/shared.js";
import { createArenaPrompt } from "./model-roles.js";

export interface CursorPluginFile {
  readonly path: string;
  readonly content: string;
}

export interface CursorPluginBundle {
  readonly pluginName: string;
  readonly files: readonly CursorPluginFile[];
}

const hookEventMap = {
  "session-start": "sessionStart",
  "before-prompt": "beforeSubmitPrompt",
  "before-tool": "preToolUse",
  "after-tool": "postToolUse",
  "after-response": "afterAgentResponse",
  "session-end": "sessionEnd",
} as const;

function oneLine(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

export function renderMstackRouterSkill(options: {
  readonly skills: readonly SkillDefinition[];
  readonly prompts: readonly PromptDefinition[];
  readonly agents: readonly AgentDefinition[];
}): string {
  // Prefer the registry playbook router (#3) when present so plugin and CLI install match.
  const registryRouter = options.skills.find((skill) => skill.id === "mstack");
  if (registryRouter) {
    const body = renderStandardSkill(registryRouter).trimEnd();
    const channelNote = [
      "",
      "## Install channel",
      "",
      "Do not mix this plugin install with a second copy of the same skills from `mstack ai setup` in the same repo.",
      "",
      "## Model roles",
      "",
      "Read `.cursor/rules/mstack-models.mdc` or `.mstack/model-roles.json` when present (`code` / `judgment` / `reviewPanel`).",
      "If unset, run `/setup-mstack` once or use the parent chat model.",
    ].join("\n");
    return `${body}\n${channelNote}`;
  }

  throw new Error("buildCursorPluginBundle requires the registry mstack workflow skill");
}

export function renderSetupMstackSkill(): string {
  return [
    "---",
    "name: setup-mstack",
    'description: "Configure mstack model roles (code, judgment, reviewPanel) and optional arena. Use for /setup-mstack or configuring mstack models."',
    "disable-model-invocation: true",
    "---",
    "",
    "<!-- Generated by mstack from Misbah's Build Like This workflow. Regenerate instead of editing. -->",
    "",
    "# Setup mstack",
    "",
    "Write an always-applied Cursor rule that maps mstack roles to models available in this session.",
    "",
    "## Steps",
    "",
    "1. Detect model slugs available to `Task` subagents in this session. Never write a slug you have not confirmed.",
    "2. Ask which install profile the user wants for future CLI installs: `lite` (smaller always-on metadata) or `full`.",
    "3. Ask whether to enable multi-model arena.",
    "4. Propose bindings for:",
    "   - `code`",
    "   - `judgment`",
    "   - `reviewPanel` (comma-separated list)",
    "5. Write `~/.cursor/rules/mstack-models.mdc` with `alwaysApply: true` using this shape:",
    "",
    "```md",
    "---",
    "description: mstack per-role model choices",
    "alwaysApply: true",
    "---",
    "# mstack model configuration",
    "code: <model>",
    "judgment: <model>",
    "reviewPanel: <model>, <model>",
    "arena: true|false",
    "```",
    "",
    "6. Also write project-local `.mstack/model-roles.json` when the repository is an mstack project, matching the CLI schema (`schemaVersion: 1`).",
    "7. Remind the user to use **one** install channel: this Cursor plugin **or** `mstack ai setup`, not both for the same skills.",
    "8. Confirm the rule applies to new sessions.",
  ].join("\n");
}

export function renderCommandMarkdown(id: string, description: string, body: string): string {
  return [
    "---",
    `name: ${yamlString(id)}`,
    `description: ${yamlString(oneLine(description))}`,
    "---",
    "",
    "<!-- Generated by mstack from Misbah's Build Like This workflow. Regenerate instead of editing. -->",
    "",
    body.trim(),
  ].join("\n");
}

export function renderCursorRule(description: string, body: string, alwaysApply = true): string {
  return [
    "---",
    `description: ${oneLine(description)}`,
    `alwaysApply: ${alwaysApply ? "true" : "false"}`,
    "---",
    "",
    "<!-- Generated by mstack from Misbah's Build Like This workflow. Regenerate instead of editing. -->",
    "",
    body.trim(),
  ].join("\n");
}

export function buildCursorPluginBundle(options: {
  readonly version: string;
  readonly spec: IntegrationSpec;
  readonly hooks: readonly HookDefinition[];
  readonly hookAssets: readonly RuntimeAsset[];
}): CursorPluginBundle {
  const pluginName = "mstack";
  const skills = options.spec.skills ?? [];
  const prompts = [...(options.spec.prompts ?? [])];
  if (!prompts.some((prompt) => prompt.id === "multi-model-arena")) {
    prompts.push(createArenaPrompt());
  }
  const agents = options.spec.agents ?? [];
  const files: CursorPluginFile[] = [];

  files.push({
    path: ".cursor-plugin/plugin.json",
    content: `${JSON.stringify({
      name: pluginName,
      displayName: "mstack",
      version: options.version,
      description:
        "Build Like This for Cursor: /mstack routes outcome-driven engineering across skills, prompts, specialists, and hooks. Prefer one install channel.",
      author: {
        name: "Misbah K.",
        email: "m.misbahkhursheed@gmail.com",
      },
      homepage: "https://misbah.lol/mstack",
      repository: "https://github.com/IMisbahk/mstack",
      license: "MIT",
      keywords: ["mstack", "build-like-this", "workflow", "skills", "agents", "engineering"],
      category: "developer-tools",
      tags: ["workflow", "planning", "review", "engineering"],
      logo: "assets/logo.svg",
      skills: "./skills/",
      agents: "./agents/",
      commands: "./commands/",
      rules: "./rules/",
      hooks: "./hooks/hooks.json",
    }, null, 2)}\n`,
  });
  files.push({
    path: "assets/logo.svg",
    content: mstackLogoSvg(),
  });

  // Entry-point skill + setup (registry mstack body; do not double-write from the skill loop)
  files.push({ path: "skills/mstack/SKILL.md", content: `${renderMstackRouterSkill({ skills, prompts, agents })}\n` });
  files.push({ path: "skills/setup-mstack/SKILL.md", content: `${renderSetupMstackSkill()}\n` });

  for (const skill of skills) {
    if (skill.id === "mstack") continue;
    files.push({ path: `skills/${skill.id}/SKILL.md`, content: `${renderStandardSkill(skill)}\n` });
  }
  for (const prompt of prompts) {
    files.push({ path: `skills/${prompt.id}/SKILL.md`, content: `${renderPromptSkill(prompt)}\n` });
  }

  files.push({
    path: "commands/mstack.md",
    content: `${renderCommandMarkdown(
      "mstack",
      "Route engineering work through Build Like This",
      "Invoke the `mstack` skill router. Follow its playbook match, todo discipline, and principle citations for this task.\n\nUser arguments: $ARGUMENTS",
    )}\n`,
  });
  files.push({
    path: "commands/setup-mstack.md",
    content: `${renderCommandMarkdown(
      "setup-mstack",
      "Configure mstack model roles and arena",
      "Invoke the `setup-mstack` skill to detect available models and write role bindings.\n\nUser arguments: $ARGUMENTS",
    )}\n`,
  });
  for (const prompt of prompts) {
    files.push({
      path: `commands/${prompt.id}.md`,
      content: `${renderCommandMarkdown(prompt.id, prompt.description, `${prompt.prompt.trim()}\n\nUser arguments: $ARGUMENTS`)}\n`,
    });
  }

  for (const agent of agents) {
    files.push({ path: `agents/${agent.id}.md`, content: `${renderAgentMarkdown(agent)}\n` });
  }

  files.push({
    path: "agents/mstack-agent.md",
    content: `${renderAgentMarkdown(
      {
        id: "mstack-agent",
        version: "1.1.0",
        description: "Routing target for /mstack. Reads the mstack skill in full before work.",
        instructions: [
          "# mstack-agent",
          "",
          "You are operating as the Build Like This router agent.",
          "Read the `mstack` skill's `SKILL.md` in full before doing any work, including its playbook routes and principle index.",
          "Do not substitute a generic subagent type that skips that read.",
        ].join("\n"),
      },
      ["is_background: true"],
    )}\n`,
  });

  files.push({
    path: "rules/build-like-this.mdc",
    content: `${renderCursorRule(
      "Misbah's Build Like This product-to-production guidance",
      renderInstructionBody(options.spec, (path) => `\`${path}\``),
      true,
    )}\n`,
  });
  files.push({
    path: "rules/mstack-models.mdc",
    content: `${renderCursorRule(
      "mstack per-role model choices (override with /setup-mstack)",
      [
        "# mstack model configuration. One line per role. Run /setup-mstack to rewrite.",
        "# code: <model>",
        "# judgment: <model>",
        "# reviewPanel: <model>, <model>",
        "# arena: false",
        "",
        "Until /setup-mstack runs, use the parent chat model for every role.",
      ].join("\n"),
      true,
    )}\n`,
  });

  const hooks: Record<string, unknown[]> = {};
  for (const hook of options.hooks) {
    const event = hookEventMap[hook.event];
    const scriptName = `${hook.id}.mjs`;
    (hooks[event] ??= []).push({
      name: hook.id,
      command: `node ./scripts/${scriptName}`,
      ...(hook.matcher === undefined ? {} : { matcher: hook.matcher }),
      ...(hook.timeoutMs === undefined ? {} : { timeout: Math.ceil(hook.timeoutMs / 1000) }),
    });
  }
  files.push({
    path: "hooks/hooks.json",
    content: `${JSON.stringify({ hooks }, null, 2)}\n`,
  });
  for (const asset of options.hookAssets) {
    const base = asset.path.split("/").pop() ?? `${asset.id}.mjs`;
    files.push({ path: `scripts/${base}`, content: asset.content.endsWith("\n") ? asset.content : `${asset.content}\n` });
  }

  return { pluginName, files };
}
